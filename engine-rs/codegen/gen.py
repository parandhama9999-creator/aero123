#!/usr/bin/env python3
"""Generates src/gen_enums.rs and src/gen_materials.rs from the data exported by the Kotlin engine
(golden/enums.json, golden/materials.json). Run from engine-rs/: python3 -I codegen/gen.py"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def snake(name):
    s = re.sub(r'(?<=[a-z0-9])([A-Z])', r'_\1', name)
    s = re.sub(r'(?<=[A-Z])([A-Z][a-z])', r'_\1', s)
    return s.lower()


def lit(s):
    return json.dumps(s, ensure_ascii=False)


def fnum(x):
    r = repr(float(x))
    return r if ('.' in r or 'e' in r or 'inf' in r or 'nan' in r) else r + '.0'


def rust_type(values):
    non_null = [v for v in values if v is not None]
    opt = len(non_null) != len(values)
    if not non_null:
        return 'Option<&\'static str>', 'opt_str'
    t0 = non_null[0]
    if isinstance(t0, bool):
        kind, rt = 'bool', 'bool'
    elif isinstance(t0, str):
        kind, rt = 'str', "&'static str"
    elif any(isinstance(v, float) for v in non_null):
        kind, rt = 'f64', 'f64'
    elif isinstance(t0, int):
        kind, rt = 'i32', 'i32'
    elif isinstance(t0, list):
        kind, rt = 'list_str', "&'static [&'static str]"
    else:
        raise ValueError(f'unsupported {t0!r}')
    if opt:
        return f'Option<{rt}>', 'opt_' + kind
    return rt, kind


def value(v, kind):
    if kind.startswith('opt_enum:'):
        return 'None' if v is None else f'Some({kind[9:]}::{v})'
    if kind.startswith('enum:'):
        return f'{kind[5:]}::{v}'
    if kind.startswith('opt_'):
        return 'None' if v is None else f'Some({value(v, kind[4:])})'
    if kind == 'bool':
        return 'true' if v else 'false'
    if kind == 'str':
        return lit(v)
    if kind == 'f64':
        return fnum(v)
    if kind == 'i32':
        return str(int(v))
    if kind == 'list_str':
        return '&[' + ', '.join(lit(x) for x in v) + ']'
    raise ValueError(kind)


ENUM_NAMES = {}


def gen_enums():
    enums = json.loads((ROOT / 'golden/enums.json').read_text())
    for n, t in enums.items():
        ENUM_NAMES[n] = {v['name'] for v in t['variants']}
    out = ['//! Generated by codegen/gen.py from the Kotlin engine\'s enums. Do not edit by hand.',
           '#![allow(non_camel_case_types, clippy::all)]', '', 'use serde::{Deserialize, Serialize};', '']
    for name, table in enums.items():
        variants = table['variants']
        names = [v['name'] for v in variants]
        props = [k for k in variants[0].keys() if k != 'name']
        out.append('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]')
        out.append(f'pub enum {name} {{')
        for n in names:
            out.append(f'    {n},')
        out.append('}')
        out.append('')
        out.append(f'impl {name} {{')
        out.append(f'    pub const VALUES: [{name}; {len(names)}] = [' + ', '.join(f'{name}::{n}' for n in names) + '];')
        out.append('    pub fn name(&self) -> &\'static str {')
        out.append('        match self {')
        for n in names:
            out.append(f'            {name}::{n} => {lit(n)},')
        out.append('        }')
        out.append('    }')
        out.append('    pub fn ordinal(&self) -> usize { *self as usize }')
        out.append('    pub fn value_of(s: &str) -> Option<Self> { Self::VALUES.iter().copied().find(|v| v.name() == s) }')
        for p in props:
            vals = [v[p] for v in variants]
            non_null = [v for v in vals if v is not None]
            ref = next((en for en, ns in ENUM_NAMES.items() if en != name and non_null and all(isinstance(v, str) and v in ns for v in non_null)
                        and len(ns) > 1), None)
            if ref:
                opt = len(non_null) != len(vals)
                rt = f'Option<{ref}>' if opt else ref
                kind = ('opt_enum:' if opt else 'enum:') + ref
            else:
                rt, kind = rust_type(vals)
            out.append(f'    pub fn {snake(p)}(&self) -> {rt} {{')
            # group equal values to keep the match short
            groups = {}
            for n, val in zip(names, vals):
                groups.setdefault(json.dumps(val, sort_keys=True), []).append(n)
            out.append('        match self {')
            for key, ns in groups.items():
                pat = ' | '.join(f'{name}::{n}' for n in ns)
                out.append(f'            {pat} => {value(json.loads(key), kind)},')
            out.append('        }')
            out.append('    }')
        out.append('}')
        out.append('')
    (ROOT / 'src/gen_enums.rs').write_text('\n'.join(out) + '\n')


HT_FIELDS = None


def ht_lit(h, ind):
    parts = []
    for k, v in h.items():
        if isinstance(v, bool):
            parts.append(f'{snake(k)}: {"true" if v else "false"}')
        else:
            parts.append(f'{snake(k)}: s({lit(v)})')
    pad = ' ' * ind
    return 'HeatTreatmentSpec {\n' + ''.join(f'{pad}    {p},\n' for p in parts) + f'{pad}}}'


def gen_materials():
    mats = json.loads((ROOT / 'golden/materials.json').read_text())
    out = ['//! Generated by codegen/gen.py from the Kotlin engine\'s DEFAULT_MATERIALS. Do not edit by hand.',
           '#![allow(clippy::all)]', '', 'use crate::catalog::{HeatTreatmentSpec, MaterialInfo};', '',
           'fn s(x: &str) -> String { x.to_string() }', '',
           '/// The default catalogue in its Kotlin order: base grades, researched grades, extended grades.',
           'pub fn default_materials() -> Vec<MaterialInfo> {', '    vec![']
    for m in mats:
        out.append('        MaterialInfo {')
        for k, v in m.items():
            f = snake(k)
            if k == 'heatTreatmentSpec':
                out.append(f'            {f}: {ht_lit(v, 12)},')
            elif k == 'estimatedFrom':
                out.append(f'            {f}: ' + ('None' if v is None else f'Some(s({lit(v)}))') + ',')
            elif k == 'dataSources':
                out.append(f'            {f}: vec![' + ', '.join(f's({lit(x)})' for x in v) + '],')
            elif isinstance(v, bool):
                out.append(f'            {f}: {"true" if v else "false"},')
            elif isinstance(v, str):
                out.append(f'            {f}: s({lit(v)}),')
            elif k == 'headingSpm':
                out.append(f'            {f}: {int(v)},')
            else:
                out.append(f'            {f}: {fnum(v)},')
        out.append('        },')
    out.append('    ]')
    out.append('}')
    (ROOT / 'src/gen_materials.rs').write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    gen_enums()
    gen_materials()
    print('generated', file=sys.stderr)
