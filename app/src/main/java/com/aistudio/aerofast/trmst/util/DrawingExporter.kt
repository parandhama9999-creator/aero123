/**
 * Images and PDF drawn off screen from the app's own geometry: the same renderers as the screens, so every
 * dimension comes from the calculation. Nothing here is generated by AI.
 */
object DrawingExporter {
    private fun f(v: Double, dp: Int = 2) = String.format(Locale.US, "%.${dp}f", v)

    /** Renders a DrawScope block into a bitmap without any view on screen. */
    fun renderBitmap(width: Int, height: Int, background: Color, block: DrawScope.() -> Unit): Bitmap {
        val image = ImageBitmap(width, height)
        val canvas = androidx.compose.ui.graphics.Canvas(image)
        CanvasDrawScope().draw(Density(1f), LayoutDirection.Ltr, canvas, Size(width.toFloat(), height.toFloat())) {
            drawRect(background)
            block()
        }
        return image.asAndroidBitmap()
    }

    private fun paint(color: Color, px: Float, bold: Boolean = false, mono: Boolean = false) = Paint().apply {
        this.color = color.toArgb(); textSize = px; isAntiAlias = true
        typeface = Typeface.create(if (mono) Typeface.MONOSPACE else Typeface.SANS_SERIF, if (bold) Typeface.BOLD else Typeface.NORMAL)
    }

    /** Splits text into lines that fit [maxWidth] for this paint. */
    fun wrap(text: String, p: Paint, maxWidth: Float): List<String> = text.split('\n').flatMap { para ->
        if (para.isEmpty()) return@flatMap listOf("")
        val out = mutableListOf<String>()
        var line = StringBuilder()
        for (word in para.split(' ')) {
            val trial = if (line.isEmpty()) word else "$line $word"
            if (p.measureText(trial) <= maxWidth || line.isEmpty()) line = StringBuilder(trial)
            else { out += line.toString(); line = StringBuilder(word) }
        }
        out += line.toString()
        out
    }

    private fun DrawScope.textLines(lines: List<Pair<String, Paint>>, x: Float, y0: Float, maxWidth: Float, lineGap: Float = 1.25f): Float {
        var y = y0
        val c = drawContext.canvas.nativeCanvas
        for ((t, p) in lines) for (l in wrap(t, p, maxWidth)) { y += p.textSize * lineGap; c.drawText(l, x, y, p) }
        return y
    }

    private fun partLine(r: FastenerCalculationResult) =
        "${r.threadLabel} × ${f(r.lengthMm, 1)} mm  ${r.fastenerType.label}  •  ${r.material.key}"

    /** Station progression with the part, machine, wire and cut-off in the title block. */
    fun progressionImage(r: FastenerCalculationResult, width: Int = 2400, height: Int = 1500): Bitmap? {
        val plan = r.headingPlan ?: return null
        val white = Color(0xFFE2E8F0)
        return renderBitmap(width, height, DieColors.background) {
            textLines(listOf(
                "AEROFAST PRO — COLD HEADING PROGRESSION" to paint(white, 44f, bold = true),
                partLine(r) to paint(white, 34f),
                "${plan.machineDescription}  •  wire Ø${f(plan.slugDiaMm)} mm  •  cut-off ${f(plan.slugLengthMm)} mm  •  head stock L/D ${f(r.upsetLdRatio)}" to paint(Color(0xFF94A3B8), 30f)
            ), 40f, 10f, width - 80f)
            inset(40f, 230f, 40f, 70f) { drawHeadingProgression(plan, textPx = 30f) }
            drawContext.canvas.nativeCanvas.drawText("Drawn from the app's calculation • dimensions in mm", 40f, height - 24f, paint(Color(0xFF64748B), 24f))
        }
    }

    /** The finished part on its own. */
    fun partImage(r: FastenerCalculationResult, width: Int = 1600, height: Int = 1200): Bitmap? {
        val last = r.headingPlan?.stations?.lastOrNull() ?: return null
        val single = HeadingPlan(last.maxWidthMm, last.heightMm, last.volumeMm3, listOf(last), emptyList(), 1, emptyList())
        val white = Color(0xFFE2E8F0)
        return renderBitmap(width, height, DieColors.background) {
            textLines(listOf(
                "FINISHED PART" to paint(white, 40f, bold = true),
                partLine(r) to paint(white, 30f),
                "Net ${f(r.netWeightGrams, 3)} g  •  slug ${f(r.grossWeightGrams, 3)} g  •  rolling blank Ø${f(r.blankTargetDia, 3)} mm" to paint(Color(0xFF94A3B8), 26f)
            ), 40f, 10f, width - 80f)
            inset(60f, 200f, 60f, 70f) { drawHeadingProgression(single, textPx = 28f, stationLabels = false) }
            drawContext.canvas.nativeCanvas.drawText("Drawn from the app's calculation • dimensions in mm", 40f, height - 24f, paint(Color(0xFF64748B), 22f))
        }
    }

    private val PRINT = ToolSectionColors(
        die = Color(0xFFD7DCE3), punch = Color(0xFFCFE3F3), part = Color(0xFFE8A04C), ko = Color(0xFF7CC4A0),
        line = Color(0xFF1F2937), bg = Color.White, label = Color(0xFF475569)
    )

    /** One station's tool section with its figures and their sources, for printing. */
    fun toolSectionImage(r: FastenerCalculationResult, st: StationTooling, width: Int = 1800, height: Int = 1150): Bitmap {
        val ink = Color(0xFF111827)
        return renderBitmap(width, height, Color.White) {
            textLines(listOf(
                "STATION ${st.station.index}: ${st.station.title.uppercase()}" to paint(ink, 38f, bold = true),
                partLine(r) to paint(Color(0xFF374151), 26f)
            ), 40f, 6f, width - 80f)
            inset(30f, 130f, width * 0.58f, 40f) { drawToolSection(st, PRINT, 26f) }
            val items = st.items.map { "${it.name}: ${it.value} [${it.basis.tag}]" to paint(ink, 22f) } +
                st.problems.map { "⛔ $it" to paint(Color(0xFFB91C1C), 22f, bold = true) }
            textLines(listOf(st.station.operation to paint(Color(0xFF4B5563), 22f)) + items, width * 0.44f, 120f, width * 0.54f, 1.3f)
        }
    }

    private fun save(bmp: Bitmap, file: File): File {
        FileOutputStream(file).use { bmp.compress(Bitmap.CompressFormat.PNG, 100, it) }
        return file
    }

    private fun safe(r: FastenerCalculationResult) = r.threadLabel.replace(Regex("[^A-Za-z0-9]+"), "_").trim('_') + "_L" + f(r.lengthMm, 0)

    /** PNG files: progression, finished part and one tool section per station. */
    fun pngFiles(context: Context, r: FastenerCalculationResult, machine: MachineSetup): List<File> {
        val dir = File(context.cacheDir, "drawings").apply { mkdirs() }
        val out = mutableListOf<File>()
        progressionImage(r)?.let { out += save(it, File(dir, "AeroFast_${safe(r)}_progression.png")) }
        partImage(r)?.let { out += save(it, File(dir, "AeroFast_${safe(r)}_part.png")) }
        ToolingDesign.build(r, machine)?.stations?.forEach { st ->
            out += save(toolSectionImage(r, st), File(dir, "AeroFast_${safe(r)}_station${st.station.index}_tooling.png"))
        }
        return out
    }

    /** A4 PDF: progression and part, every station's tool section, the tooling sheet and the production report. */
    fun pdfFile(context: Context, r: FastenerCalculationResult, machine: MachineSetup): File {
        val dir = File(context.cacheDir, "drawings").apply { mkdirs() }
        val file = File(dir, "AeroFast_${safe(r)}_drawings.pdf")
        val doc = PdfDocument()
        val pageW = 595; val pageH = 842; val margin = 28f
        var pageNo = 0
        fun newPage(): PdfDocument.Page = doc.startPage(PdfDocument.PageInfo.Builder(pageW, pageH, ++pageNo).create())
        fun drawImage(page: PdfDocument.Page, bmp: Bitmap, top: Float, maxH: Float): Float {
            val w = pageW - 2 * margin
            val h = minOf(maxH, w * bmp.height / bmp.width)
            val ww = h * bmp.width / bmp.height
            page.canvas.drawBitmap(bmp, null, android.graphics.RectF(margin, top, margin + ww, top + h), Paint(Paint.FILTER_BITMAP_FLAG))
            return top + h
        }
        // Page 1: progression + part
        newPage().let { pg ->
            var y = margin
            progressionImage(r)?.let { y = drawImage(pg, it, y, 360f) + 14f }
            partImage(r)?.let { drawImage(pg, it, y, pageH - y - margin) }
            doc.finishPage(pg)
        }
        // Tool sections, two per page
        val sheet = ToolingDesign.build(r, machine)
        sheet?.stations?.chunked(2)?.forEach { pair ->
            val pg = newPage()
            var y = margin
            pair.forEach { st -> y = drawImage(pg, toolSectionImage(r, st), y, (pageH - 3 * margin) / 2f) + margin }
            doc.finishPage(pg)
        }
        // Text pages
        val textPaint = Paint().apply { textSize = 7.2f; typeface = Typeface.MONOSPACE; color = android.graphics.Color.BLACK; isAntiAlias = true }
        val texts = listOfNotNull(sheet?.let { ToolingDesign.text(r, it, machine) }, ProductionReport.build(r))
        for (t in texts) {
            val lines = wrap(t, textPaint, pageW - 2 * margin)
            val perPage = ((pageH - 2 * margin) / (textPaint.textSize * 1.25f)).toInt()
            lines.chunked(perPage).forEach { chunk ->
                val pg = newPage()
                var y = margin
                chunk.forEach { l -> y += textPaint.textSize * 1.25f; pg.canvas.drawText(l, margin, y, textPaint) }
                doc.finishPage(pg)
            }
        }
        FileOutputStream(file).use { doc.writeTo(it) }
        doc.close()
        return file
    }

    /** Opens the share sheet for one or more files. */
    fun share(context: Context, files: List<File>, mime: String, subject: String) {
        if (files.isEmpty()) return
        val uris = ArrayList(files.map { FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", it) })
        val intent = if (uris.size == 1) Intent(Intent.ACTION_SEND).apply { putExtra(Intent.EXTRA_STREAM, uris[0]) }
            else Intent(Intent.ACTION_SEND_MULTIPLE).apply { putParcelableArrayListExtra(Intent.EXTRA_STREAM, uris) }
        intent.type = mime
        intent.putExtra(Intent.EXTRA_SUBJECT, subject)
        intent.addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        context.startActivity(Intent.createChooser(intent, subject).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
    }
}
