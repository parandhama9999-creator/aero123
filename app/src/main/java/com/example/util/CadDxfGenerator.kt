package com.example.util

import android.content.Context
import android.content.Intent
import android.net.Uri
import androidx.core.content.FileProvider
import com.example.data.FastenerCalculationResult
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object CadDxfGenerator {

    fun generateCadDxfSpecText(result: FastenerCalculationResult): String {
        val dateFormat = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US)
        val timestamp = dateFormat.format(Date())

        val d = result.nominalDiaMm
        val p = result.pitchMm
        val l = result.lengthMm
        val lt = result.threadLengthMm
        val blank = result.blankTargetDia
        val headWidth = d * 1.5
        val headHeight = d * 0.7

        val sb = StringBuilder()
        sb.append("0\nSECTION\n2\nHEADER\n9\n\$ACADVER\n1\nAC1015\n0\nENDSEC\n")
        sb.append("0\nSECTION\n2\nTABLES\n0\nENDSEC\n")
        sb.append("0\nSECTION\n2\nENTITIES\n")

        // 1. Centerline Axis
        sb.append("0\nLINE\n8\nAXIS\n10\n0.0\n20\n-${headHeight + 5.0}\n30\n0.0\n11\n0.0\n21\n${l + 5.0}\n31\n0.0\n")

        // 2. Head Profile (Upper Half)
        sb.append("0\nLINE\n8\nOUTLINE\n10\n0.0\n20\n0.0\n30\n0.0\n11\n${headWidth / 2.0}\n21\n0.0\n")
        sb.append("0\nLINE\n8\nOUTLINE\n10\n${headWidth / 2.0}\n20\n0.0\n30\n0.0\n11\n${headWidth / 2.0}\n21\n$headHeight\n31\n0.0\n")
        sb.append("0\nLINE\n8\nOUTLINE\n10\n${headWidth / 2.0}\n20\n$headHeight\n30\n0.0\n11\n${d / 2.0}\n21\n$headHeight\n31\n0.0\n")

        // 3. Shank & Thread Profile
        sb.append("0\nLINE\n8\nOUTLINE\n10\n${d / 2.0}\n20\n$headHeight\n30\n0.0\n11\n${d / 2.0}\n21\n$l\n31\n0.0\n")
        sb.append("0\nLINE\n8\nOUTLINE\n10\n${d / 2.0}\n20\n$l\n30\n0.0\n11\n0.0\n21\n$l\n31\n0.0\n")

        // 4. Thread representation
        val threadStartZ = l - lt
        var z = threadStartZ
        while (z < l - p) {
            sb.append("0\nLINE\n8\nTHREADS\n10\n${d / 2.0}\n20\n$z\n30\n0.0\n11\n${blank / 2.0}\n21\n${z + p / 2.0}\n31\n0.0\n")
            sb.append("0\nLINE\n8\nTHREADS\n10\n${blank / 2.0}\n20\n${z + p / 2.0}\n30\n0.0\n11\n${d / 2.0}\n21\n${z + p}\n31\n0.0\n")
            z += p
        }

        sb.append("0\nENDSEC\n0\nEOF\n\n")

        // Parametric Summary Header
        sb.append("========================================================\n")
        sb.append("         AEROFAST PRO - CAD & DXF PARAMETRIC SPEC       \n")
        sb.append("========================================================\n")
        sb.append(" Generated Timestamp: $timestamp\n")
        sb.append(" Part Name      : ${result.threadLabel}\n")
        sb.append(" Standard       : ${result.standard.code} (${result.standard.label})\n")
        sb.append(" Nominal Diameter: $d mm\n")
        sb.append(" Pitch          : $p mm\n")
        sb.append(" Total Length   : $l mm\n")
        sb.append(" Thread Length  : $lt mm\n")
        sb.append(" Pre-Roll Blank : $blank mm\n")
        sb.append(" Head Width A/F : ${headWidth.round(2)} mm\n")
        sb.append(" Head Height    : ${headHeight.round(2)} mm\n")
        sb.append(" Material Grade : ${result.material.name}\n")
        sb.append("========================================================\n")

        return sb.toString()
    }

    private fun Double.round(decimals: Int): Double {
        var multiplier = 1.0
        repeat(decimals) { multiplier *= 10.0 }
        return kotlin.math.round(this * multiplier) / multiplier
    }

    fun exportAndShareCadDxf(context: Context, result: FastenerCalculationResult) {
        try {
            val dxfContent = generateCadDxfSpecText(result)
            val fileName = "AeroFast_CAD_Model_${result.threadLabel.replace(Regex("[^a-zA-Z0-9]"), "_")}.dxf"
            val file = File(context.cacheDir, fileName)
            FileOutputStream(file).use { fos ->
                fos.write(dxfContent.toByteArray())
            }

            val uri: Uri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                file
            )

            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "application/dxf"
                putExtra(Intent.EXTRA_STREAM, uri)
                putExtra(Intent.EXTRA_SUBJECT, "AeroFast Pro CAD DXF Model - ${result.threadLabel}")
                putExtra(Intent.EXTRA_TEXT, "Attached is the parametric 2D DXF vector drawing and CAD parameter sheet generated by AeroFast Pro.")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }

            val chooser = Intent.createChooser(intent, "Export CAD DXF Drawing")
            chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            context.startActivity(chooser)
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }
}
